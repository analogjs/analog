/**
 * Position mapping for the TSRX → Angular lowering.
 *
 * The lowering generates TypeScript text out of pieces of the original `.tsrx`
 * source. `MappedText` records where every generated character came from so
 * that diagnostics and emitted source maps can point back at the TSRX.
 */

import {
  decode,
  encode,
  type SourceMapMappings,
  type SourceMapSegment,
} from '@jridgewell/sourcemap-codec';

/** A half-open range of offsets into the original source. */
export interface Span {
  start: number;
  end: number;
}

/**
 * A region of generated text and the region of the original TSX it came from.
 *
 * Exact segments are verbatim copies, so offsets inside them map one-to-one. Inexact segments are
 * synthesized code standing in for an original node; every offset inside them maps to that
 * node's span. Segments nest. The innermost segment containing an offset wins.
 */
interface Segment {
  genStart: number;
  genEnd: number;
  origStart: number;
  origEnd: number;
  exact: boolean;
}

/**
 * Text being generated by the TSX lowering, together with where each part of it came from.
 */
export class MappedText {
  text = '';
  readonly segments: Segment[] = [];

  /** Appends synthesized text, or another `MappedText` together with its mappings. */
  append(part: string | MappedText): this {
    if (typeof part === 'string') {
      this.text += part;
    } else {
      const offset = this.text.length;
      for (const s of part.segments) {
        this.segments.push({
          ...s,
          genStart: s.genStart + offset,
          genEnd: s.genEnd + offset,
        });
      }
      this.text += part.text;
    }
    return this;
  }

  /** Appends a verbatim copy of `span` of `originalText`. */
  copy(originalText: string, span: Span): this {
    return this.copyRange(originalText, span.start, span.end);
  }

  /** Appends a verbatim copy of `originalText.slice(start, end)`. */
  copyRange(originalText: string, start: number, end: number): this {
    const genStart = this.text.length;
    this.text += originalText.slice(start, end);
    this.segments.push({
      genStart,
      genEnd: this.text.length,
      origStart: start,
      origEnd: end,
      exact: true,
    });
    return this;
  }

  /**
   * Attributes everything appended so far that isn't already mapped more precisely to `span`.
   */
  from(span: Span): this {
    this.segments.push({
      genStart: 0,
      genEnd: this.text.length,
      origStart: span.start,
      origEnd: span.end,
      exact: false,
    });
    return this;
  }
}

/**
 * Tagged template for building `MappedText`: `mt\`@if (${cond}) {${body}}\``. Interpolated
 * `MappedText` values keep their mappings.
 */
export function mt(
  strings: TemplateStringsArray,
  ...values: (string | MappedText)[]
): MappedText {
  const out = new MappedText();
  strings.forEach((s, i) => {
    out.append(s);
    if (i < values.length) {
      out.append(values[i]);
    }
  });
  return out;
}

/** Joins mapped parts with a separator. */
export function joinMapped(
  parts: readonly (string | MappedText)[],
  separator: string,
): MappedText {
  const out = new MappedText();
  parts.forEach((p, i) => {
    if (i > 0) {
      out.append(separator);
    }
    out.append(p);
  });
  return out;
}

/**
 * Serializes `content` as a JSON string literal, keeping its mappings aligned with the escaped
 * characters. This is what lets template diagnostics, which Angular reports against the raw
 * bytes of an inline template, map back to the TSX that produced them.
 */
export function jsonLiteral(content: MappedText): MappedText {
  // `offsets[i]` is the position of `content.text[i]` within the literal, including the quote.
  const offsets: number[] = [];
  let literal = '"';
  for (let i = 0; i < content.text.length; i++) {
    offsets.push(literal.length);
    literal += JSON.stringify(content.text[i]).slice(1, -1);
  }
  offsets.push(literal.length);
  literal += '"';

  const out = new MappedText();
  out.text = literal;
  for (const s of content.segments) {
    out.segments.push({
      ...s,
      genStart: offsets[s.genStart],
      genEnd: offsets[s.genEnd],
    });
  }
  return out;
}

/**
 * Maps positions in the lowered source of a `.tsrx` file back to the original TSRX.
 */
export class TsrxSourceMap {
  /** Non-overlapping intervals of generated text, each with its innermost segment. */
  private readonly intervals: {
    start: number;
    end: number;
    segment: Segment;
  }[] = [];
  private generatedLineStarts: readonly number[] | null = null;
  private originalLineStarts: readonly number[] | null = null;

  constructor(
    readonly fileName: string,
    readonly originalText: string,
    readonly generatedText: string,
    segments: readonly Segment[],
  ) {
    // Sweep the (properly nested) segments, outermost first, emitting the innermost segment for
    // each stretch of generated text.
    const sorted = segments
      .filter((s) => s.genEnd > s.genStart)
      .sort((a, b) => a.genStart - b.genStart || b.genEnd - a.genEnd);
    const stack: Segment[] = [];
    let cursor = 0;
    const emitUpTo = (pos: number) => {
      if (stack.length > 0 && pos > cursor) {
        this.intervals.push({
          start: cursor,
          end: pos,
          segment: stack[stack.length - 1],
        });
      }
      cursor = Math.max(cursor, pos);
    };
    for (const seg of sorted) {
      while (
        stack.length > 0 &&
        stack[stack.length - 1].genEnd <= seg.genStart
      ) {
        emitUpTo(stack[stack.length - 1].genEnd);
        stack.pop();
      }
      emitUpTo(seg.genStart);
      stack.push(seg);
    }
    while (stack.length > 0) {
      emitUpTo(stack[stack.length - 1].genEnd);
      stack.pop();
    }
  }

  /** Builds the map for a file assembled as `text`. */
  static fromMappedText(
    fileName: string,
    originalText: string,
    text: MappedText,
  ): TsrxSourceMap {
    return new TsrxSourceMap(fileName, originalText, text.text, text.segments);
  }

  /**
   * Maps a span of generated text to the original TSX, or returns `null` for generated
   * boilerplate that has no counterpart in the original.
   */
  toOriginalSpan(
    start: number,
    length: number,
  ): { start: number; length: number } | null {
    const interval = this.find(start);
    if (interval === null) {
      return null;
    }
    const seg = interval.segment;
    if (!seg.exact) {
      return { start: seg.origStart, length: seg.origEnd - seg.origStart };
    }
    const origStart = seg.origStart + (start - seg.genStart);
    const origEnd = Math.min(origStart + length, seg.origEnd);
    return { start: origStart, length: Math.max(origEnd - origStart, 0) };
  }

  /** Maps a single generated offset to an original offset, or `null` for boilerplate. */
  toOriginalOffset(pos: number): number | null {
    const interval = this.find(pos);
    if (interval === null) {
      return null;
    }
    const seg = interval.segment;
    return seg.exact ? seg.origStart + (pos - seg.genStart) : seg.origStart;
  }

  /** Maps a zero-based generated line/column to an original one. */
  toOriginalLineAndColumn(
    line: number,
    column: number,
  ): { line: number; column: number } | null {
    const generated = (this.generatedLineStarts ??= lineStarts(
      this.generatedText,
    ));
    const starts = (this.originalLineStarts ??= lineStarts(this.originalText));
    if (line >= generated.length) {
      return null;
    }
    const offset = this.toOriginalOffset(generated[line] + column);
    if (offset === null) {
      return null;
    }
    let lo = 0;
    let hi = starts.length - 1;
    while (lo < hi) {
      const mid = (lo + hi + 1) >> 1;
      if (starts[mid] <= offset) {
        lo = mid;
      } else {
        hi = mid - 1;
      }
    }
    return { line: lo, column: offset - starts[lo] };
  }

  private find(
    pos: number,
  ): { start: number; end: number; segment: Segment } | null {
    let lo = 0;
    let hi = this.intervals.length - 1;
    while (lo <= hi) {
      const mid = (lo + hi) >> 1;
      const interval = this.intervals[mid];
      if (pos < interval.start) {
        hi = mid - 1;
      } else if (pos >= interval.end) {
        lo = mid + 1;
      } else {
        return interval;
      }
    }
    return null;
  }
}

/** Offsets at which each line of `text` starts, with the same line breaks as TypeScript. */
function lineStarts(text: string): number[] {
  const starts = [0];
  for (let i = 0; i < text.length; i++) {
    const ch = text.charCodeAt(i);
    if (ch === 13 /* \r */) {
      if (text.charCodeAt(i + 1) === 10 /* \n */) {
        i++;
      }
      starts.push(i + 1);
    } else if (ch === 10 || ch === 0x2028 || ch === 0x2029) {
      starts.push(i + 1);
    }
  }
  return starts;
}

interface RawSourceMap {
  version: number;
  sources: string[];
  sourcesContent?: (string | null)[];
  mappings: string;
  [key: string]: unknown;
}

/**
 * Rewrites a source map emitted for a lowered `.tsrx` file so that it points at the original
 * TSRX. Mappings into synthesized boilerplate are dropped, and `sourcesContent` (when present)
 * is replaced with the original source.
 *
 * @param json The emitted source map.
 * @param map The lowering map of the `.tsrx` file.
 */
export function remapSourceMap(json: string, map: TsrxSourceMap): string {
  const raw = JSON.parse(json) as RawSourceMap;
  const base = map.fileName.slice(map.fileName.lastIndexOf('/') + 1);
  // The program file of `Counter.tsrx` is `Counter.tsrx.ts`.
  const matches = (source: string) =>
    [base, base + '.ts'].some((b) => source === b || source.endsWith('/' + b));
  const sourceIndex =
    raw.sources.length === 1 ? 0 : raw.sources.findIndex(matches);
  if (sourceIndex === -1) {
    return json;
  }

  const mappings: SourceMapMappings = decode(raw.mappings).map((line) => {
    const out: SourceMapSegment[] = [];
    for (const segment of line) {
      if (segment.length === 1 || segment[1] !== sourceIndex) {
        out.push(segment);
        continue;
      }
      const original = map.toOriginalLineAndColumn(segment[2], segment[3]);
      if (original === null) {
        // Synthesized code: keep the generated position, but with no source.
        out.push([segment[0]]);
      } else if (segment.length === 5) {
        out.push([
          segment[0],
          segment[1],
          original.line,
          original.column,
          segment[4],
        ]);
      } else {
        out.push([segment[0], segment[1], original.line, original.column]);
      }
    }
    return out;
  });

  raw.mappings = encode(mappings);
  raw.sources[sourceIndex] = stripProgramSuffix(raw.sources[sourceIndex]);
  if (
    raw.sourcesContent !== undefined &&
    raw.sourcesContent[sourceIndex] != null
  ) {
    raw.sourcesContent[sourceIndex] = map.originalText;
  }
  return JSON.stringify(raw);
}

/** `Counter.tsrx.ts` (a program file name) → `Counter.tsrx`. */
function stripProgramSuffix(source: string): string {
  return source.endsWith('.tsrx.ts') ? source.slice(0, -'.ts'.length) : source;
}
